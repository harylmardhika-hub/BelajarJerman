function deduplicateVocabulary(items: VocabItem[]): VocabItem[] {
  const seen = new Set<string>();
  const result: VocabItem[] = [];
  for (const item of items) {
    const key = item.word.trim().toLowerCase();
    if (!seen.has(key)) {
      seen.add(key);
      result.push(item);
    }
  }
  return result;
}

